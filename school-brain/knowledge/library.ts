export function getBookById(id: string): LibraryBook | undefined {
  return LIBRARY_BOOKS.find((book) => book.id === id);
}

export function searchBooks(query: string): LibraryBook[] {
  const lower = query.toLowerCase();
  return LIBRARY_BOOKS.filter(
    (book) =>
      book.title.toLowerCase().includes(lower) ||
      book.author.toLowerCase().includes(lower) ||
      book.category.toLowerCase().includes(lower) ||
      book.isbn.includes(query)
  );
}

export function getBooksByCategory(category: string): LibraryBook[] {
  return LIBRARY_BOOKS.filter(
    (book) => book.category.toLowerCase() === category.toLowerCase()
  );
}

export function getIssuedBooksByStudent(studentId: string): IssuedBook[] {
  return ISSUED_BOOKS.filter((issue) => issue.studentId === studentId);
}

export function getOverdueBooks(): IssuedBook[] {
  return ISSUED_BOOKS.filter((issue) => issue.status === 'overdue');
}

export function getAvailableBooks(): LibraryBook[] {
  return LIBRARY_BOOKS.filter((book) => book.availableCopies > 0);
}
